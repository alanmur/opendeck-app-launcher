// "pt-br" -> "pt_BR", "sr@Latin" -> "sr@latin"
function normalizeLanguage(code) {
	const m = /^([a-zA-Z]{2,3})(?:[-_]([a-zA-Z]{2}))?(?:@([a-zA-Z]+))?$/.exec((code || "").trim());
	if (!m) return null;
	return m[1].toLowerCase() + (m[2] ? "_" + m[2].toUpperCase() : "") + (m[3] ? "@" + m[3].toLowerCase() : "");
}

// Native name for a code, falling back to the base language: "es_MX" -> "Español (es_MX)".
function languageName(code) {
	const norm = normalizeLanguage(code);
	if (!norm) return null;
	if (LANGUAGES[norm]) return LANGUAGES[norm];
	const base = norm.split(/[_@]/)[0];
	return LANGUAGES[base] ? `${LANGUAGES[base]} (${norm})` : null;
}
